def _static() -> dict[str, str]:
    table = dict(_KY_OTHER)
    for src, dst in ((REASONS, KY_REASONS), (ADVICE, KY_ADVICE),
                     (RULE_ADVICE, KY_RULE_ADVICE)):
        for name, text in src.items():
            if name in dst:
                table[text] = dst[name]
    for name, text in RULE_REASONS.items():
        if name in KY_RULE_REASONS and "{" not in text:
            table[text] = KY_RULE_REASONS[name]
    return table


_STATIC = _static()


def _details(text: str) -> str:
    return "; ".join(translate(part, "ky") for part in text.split("; "))


def _brand_mismatch_re() -> re.Pattern:
    tpl = re.escape(RULE_REASONS["brand_mismatch"])
    tpl = tpl.replace(re.escape("{brand}"), "(?P<brand>.+?)").replace(re.escape("{host}"), "(?P<host>.+)")
    return re.compile(tpl)


