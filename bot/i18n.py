def translate(text: str, lang: str) -> str:
    """Причина или совет из check() на нужном языке (ru — без изменений)."""
    if lang != "ky":
        return text
    if text in _STATIC:
        return _STATIC[text]
    for pattern, render in _PATTERNS:
        m = pattern.fullmatch(text)
        if m:
            return render(m)
    return text


