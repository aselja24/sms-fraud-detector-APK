"""
Таблицы символов для разбора адресов ссылок (используются entities.py,
links.py и normalize.py).

INVISIBLE_RE  — невидимые символы (нулевой пробел, мягкий перенос и т.п.):
                мошенники вставляют их внутрь адреса, чтобы он выглядел
                как настоящий, а программа видела другой.
CONFUSABLE    — буквы других алфавитов, которые глазом неотличимы от
                латинских: кириллица, греческие, ı, ɡ, ӏ.
CYR_TO_LAT    — обычная транслитерация: адрес целиком кириллицей
                («бакай.кг») выдаёт себя за bakai.kg.
TLD_CYR       — доменные зоны, написанные кириллицей («mbank.кг»).
"""
import re

INVISIBLE_RE = re.compile("[­​-‏‪-‮⁠﻿]")

CONFUSABLE = {
    # кириллица
    "а": "a", "е": "e", "о": "o", "р": "p", "с": "c", "х": "x", "у": "y",
    "к": "k", "м": "m", "т": "t", "в": "b", "і": "i", "ѕ": "s", "ј": "j",
    "ԁ": "d", "ԝ": "w", "ӏ": "l", "ԛ": "q",
    # греческие
    "ο": "o", "α": "a", "ν": "v", "ρ": "p", "τ": "t", "ι": "i", "κ": "k",
    "χ": "x", "υ": "u", "ε": "e",
    # прочие латинские look-alike
    "ı": "i", "ɡ": "g",
}

CYR_TO_LAT = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "zh", "з": "z", "и": "i", "й": "i", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "h", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "sh", "ъ": "",
    "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
    # кыргызские буквы
    "ө": "o", "ү": "u", "ң": "n",
}

# Доменные зоны, написанные кириллицей. Ключ — как в тексте (нижний регистр).
TLD_CYR = {
    "кг": "kg", "ком": "com", "нет": "net", "орг": "org", "ру": "ru",
    "инфо": "info", "топ": "top", "сайт": "site",
}


def transliterate(text: str) -> str:
    """Кириллица -> латиница по CYR_TO_LAT; остальные символы не трогаем."""
    return "".join(CYR_TO_LAT.get(ch, ch) for ch in text.lower())


def tld_key(tld: str) -> str:
    """Зона в виде латиницы: «кг» -> «kg», «кg» -> «kg», «com» -> «com»."""
    key = tld.lower()
    if key in TLD_CYR:
        return TLD_CYR[key]
    return "".join(CONFUSABLE.get(ch, ch) for ch in key)
